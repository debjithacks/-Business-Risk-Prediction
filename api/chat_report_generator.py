from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)

from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors
from datetime import datetime


def generate_chat_history_report(chat_data):

    file_path = (
        f"chat_history_"
        f"{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
    )

    styles = getSampleStyleSheet()

    elements = []

    # =========================
    # HEADER
    # =========================

    elements.append(
        Paragraph(
            "<font size=16><b>Business Risk Prediction System</b></font>",
            styles["Title"]
        )
    )

    elements.append(Spacer(1, 4))

    elements.append(
        Paragraph(
            "<font size=14><b>Chat History Report</b></font>",
            styles["Heading2"]
        )
    )

    elements.append(Spacer(1, 6))

    elements.append(
        Paragraph(
            f"<b>Generated On:</b> "
            f"{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            styles["Normal"]
        )
    )

    elements.append(Spacer(1, 15))

    # =========================
    # CHAT MESSAGES
    # =========================

    for chat in chat_data:

        user_msg = chat.get("message", "")
        bot_reply = chat.get("reply", "")

        timestamp = chat.get("timestamp")

        if timestamp:
            time_text = timestamp.strftime("%Y-%m-%d %H:%M:%S")
        else:
            time_text = "Unknown Time"

        # USER PARAGRAPH

        user_paragraph = Paragraph(
            f"<b>User ({time_text})</b><br/>{user_msg}",
            styles["Normal"]
        )

        user_table = Table(
            [[user_paragraph]],
            colWidths=[460]
        )

        user_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.whitesmoke),
                ("BOX", (0, 0), (-1, -1), 1, colors.grey),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ])
        )

        elements.append(user_table)

        elements.append(Spacer(1, 6))

        # BOT PARAGRAPH

        bot_paragraph = Paragraph(
            f"<b>Bot ({time_text})</b><br/>{bot_reply}",
            styles["Normal"]
        )

        bot_table = Table(
            [[bot_paragraph]],
            colWidths=[460]
        )

        bot_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.lightblue),
                ("BOX", (0, 0), (-1, -1), 1, colors.blue),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ])
        )

        elements.append(bot_table)

        elements.append(Spacer(1, 12))

    # =========================
    # FOOTER TEXT
    # =========================

    elements.append(Spacer(1, 20))

    elements.append(
        Paragraph(
            "<font size=9 color=grey>"
            "Generated by Business Risk Prediction System"
            "</font>",
            styles["Normal"]
        )
    )

    # =========================
    # PAGE NUMBER FUNCTION
    # =========================

    def add_page_number(canvas, doc):

        canvas.saveState()

        page_number_text = f"Page {doc.page}"

        canvas.drawRightString(
            550,
            20,
            page_number_text
        )

        canvas.restoreState()

    # =========================
    # BUILD PDF
    # =========================

    doc = SimpleDocTemplate(

        file_path,

        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=50

    )

    doc.build(

        elements,

        onFirstPage=add_page_number,
        onLaterPages=add_page_number

    )

    return file_path